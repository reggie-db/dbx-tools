import { afterEach, expect, test } from "bun:test";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { collectUndocumentedPublicSymbols } from "./check-source-docs.mjs";

const temporaryDirectories = [];

afterEach(() => {
  for (const directory of temporaryDirectories.splice(0)) {
    fs.rmSync(directory, { force: true, recursive: true });
  }
});

test("checks owning declarations once and ignores generated exports", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "dbx-tools-source-docs-"));
  temporaryDirectories.push(root);
  const pkg = path.join(root, "packages", "js", "shared", "example");
  fs.mkdirSync(path.join(pkg, "src"), { recursive: true });
  fs.writeFileSync(
    path.join(pkg, "package.json"),
    `${JSON.stringify(
      {
        name: "@scope/example",
        exports: {
          ".": "./src/index.ts",
          "./generated": "./src/generated.ts",
        },
      },
      null,
      2,
    )}\n`,
  );
  fs.writeFileSync(
    path.join(pkg, "src", "index.ts"),
    [
      "/** Documented public value. */",
      "export const documented = true;",
      "export const undocumented = true;",
      "export { undocumented as legacyUndocumented };",
      "",
    ].join("\n"),
  );
  fs.writeFileSync(
    path.join(pkg, "src", "generated.ts"),
    ["// GENERATED by a fixture - DO NOT EDIT.", "export const generatedValue = true;", ""].join(
      "\n",
    ),
  );

  expect(collectUndocumentedPublicSymbols(root)).toEqual([
    expect.objectContaining({
      package: "@scope/example",
      name: "undocumented",
      source: "packages/js/shared/example/src/index.ts",
      exports: ["@scope/example#legacyUndocumented", "@scope/example#undocumented"],
    }),
  ]);
});
