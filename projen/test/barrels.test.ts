import assert from "node:assert/strict";
import {
  chmodSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, it } from "node:test";

import { folderBarrelFile, generateBarrels } from "../src/barrels.ts";

function fixturePackage(name: string): string {
  const directory = join(mkdtempSync(join(tmpdir(), "dbx-tools-barrels-")), name);
  mkdirSync(join(directory, "src"), { recursive: true });
  writeFileSync(
    join(directory, "package.json"),
    `${JSON.stringify({ name: `@test/${name}`, version: "1.2.3" }, null, 2)}\n`,
  );
  writeFileSync(join(directory, "src", "graph.ts"), 'export const graphValue = "x";\n');
  return directory;
}

function barrelStat(directory: string, file = "index.ts"): [number, number, number] {
  const stat = statSync(join(directory, file));
  return [stat.mode & 0o777, stat.mtimeMs, stat.ctimeMs];
}

describe("generateBarrels", () => {
  it("keeps a metadata-only root barrel for an empty source tree", () => {
    const directory = fixturePackage("empty-root");
    rmSync(join(directory, "src", "graph.ts"));

    assert.equal(generateBarrels({ dirs: [directory] }), 1);
    const barrel = readFileSync(join(directory, "index.ts"), "utf8");
    assert.match(barrel, /export const PACKAGE_IDENTIFIER = "@test\/empty-root";/);
    assert.match(barrel, /export const PACKAGE_VERSION = "1\.2\.3";/);
  });

  it("writes module namespaces and conflict-free flat exports", () => {
    const directory = fixturePackage("fresh");

    assert.equal(generateBarrels({ dirs: [directory] }), 1);

    const barrel = readFileSync(join(directory, "index.ts"), "utf8");
    assert.match(barrel, /^\/\/ GENERATED by projen watch - DO NOT EDIT\./);
    assert.match(barrel, /export const PACKAGE_IDENTIFIER = "@test\/fresh";/);
    assert.match(barrel, /export const PACKAGE_VERSION = "1\.2\.3";/);
    assert.match(barrel, /export \* as graph from "\.\/src\/graph\.ts";/);
    assert.match(barrel, /export \{ graphValue \} from "\.\/src\/graph\.ts";/);
    assert.equal(barrelStat(directory)[0], 0o444);
  });

  it("generates root-level barrels for every source folder", () => {
    const directory = fixturePackage("folders");
    mkdirSync(join(directory, "src", "example", "wasm"), { recursive: true });
    writeFileSync(
      join(directory, "src", "example", "one.ts"),
      [
        "export const one = 1;",
        "export interface One { value: number }",
        "export function run(): number { return one; }",
        "",
      ].join("\n"),
    );
    writeFileSync(
      join(directory, "src", "example", "wasm", "loader.ts"),
      "export const load = 2;\n",
    );

    assert.equal(generateBarrels({ dirs: [directory] }), 3);

    const root = readFileSync(join(directory, "index.ts"), "utf8");
    const example = readFileSync(join(directory, "index.example.ts"), "utf8");
    const wasm = readFileSync(join(directory, "index.example.wasm.ts"), "utf8");
    assert.match(root, /export \* as graph from "\.\/src\/graph\.ts";/);
    assert.doesNotMatch(root, /\.\/src\/example\//);
    assert.doesNotMatch(example, /export \* as one from "\.\/src\/example\/one\.ts";/);
    assert.match(example, /export \{ one, run \} from "\.\/src\/example\/one\.ts";/);
    assert.match(example, /export type \{ One \} from "\.\/src\/example\/one\.ts";/);
    assert.doesNotMatch(example, /index\.example\.wasm/);
    assert.match(wasm, /export \* as loader from "\.\/src\/example\/wasm\/loader\.ts";/);
    assert.match(wasm, /export \{ load \} from "\.\/src\/example\/wasm\/loader\.ts";/);
    assert.throws(() => statSync(join(directory, "src", "example", "index.ts")), {
      code: "ENOENT",
    });
  });

  it("derives deterministic dotted folder barrel names", () => {
    assert.equal(folderBarrelFile("auth/react"), "index.auth.react.ts");
    assert.equal(folderBarrelFile("genie-code"), "index.genie-code.ts");
  });

  it("rejects hand-written nested source indexes", () => {
    const directory = fixturePackage("nested-index");
    mkdirSync(join(directory, "src", "example"), { recursive: true });
    writeFileSync(join(directory, "src", "example", "index.ts"), "export const value = 1;\n");

    assert.throws(
      () => generateBarrels({ dirs: [directory] }),
      (error: unknown) => {
        assert.ok(error instanceof AggregateError);
        assert.match(String(error.errors[0]), /Nested source index is unsupported/);
        return true;
      },
    );
  });

  it("removes stale root-level folder barrels", () => {
    const directory = fixturePackage("folder-cleanup");
    mkdirSync(join(directory, "src", "example"), { recursive: true });
    const module = join(directory, "src", "example", "one.ts");
    writeFileSync(module, "export const one = 1;\n");
    generateBarrels({ dirs: [directory] });
    rmSync(module);

    assert.equal(generateBarrels({ dirs: [directory] }), 1);
    assert.throws(() => statSync(join(directory, "index.example.ts")), { code: "ENOENT" });
  });

  it("leaves unchanged read-only barrels byte-for-byte and stat-for-stat alone", async () => {
    const directory = fixturePackage("noop");
    generateBarrels({ dirs: [directory] });
    const before = barrelStat(directory);
    await new Promise((resolve) => setTimeout(resolve, 10));

    assert.equal(generateBarrels({ dirs: [directory] }), 0);
    assert.deepEqual(barrelStat(directory), before);
    assert.equal(before[0], 0o444);
  });

  it("restores read-only mode on unchanged barrels", () => {
    const directory = fixturePackage("restore-mode");
    generateBarrels({ dirs: [directory] });
    const barrel = join(directory, "index.ts");
    const content = readFileSync(barrel, "utf8");
    chmodSync(barrel, 0o644);

    assert.equal(generateBarrels({ dirs: [directory] }), 0);
    assert.equal(readFileSync(barrel, "utf8"), content);
    assert.equal(barrelStat(directory)[0], 0o444);
  });

  it("rewrites read-only barrels and restores their mode", () => {
    const directory = fixturePackage("grow");
    generateBarrels({ dirs: [directory] });
    writeFileSync(join(directory, "src", "edge.ts"), "export const edge = true;\n");

    assert.equal(generateBarrels({ dirs: [directory] }), 1);
    assert.match(readFileSync(join(directory, "index.ts"), "utf8"), /export \{ edge \} from/);
    assert.equal(barrelStat(directory)[0], 0o444);
  });

  it("attempts every package and reports failures together", () => {
    const broken = fixturePackage("broken");
    mkdirSync(join(broken, "index.ts"), { recursive: true });
    const healthy = fixturePackage("healthy");

    assert.throws(
      () => generateBarrels({ dirs: [broken, healthy] }),
      (error: unknown) => {
        assert.ok(error instanceof AggregateError);
        assert.match(error.message, /1 barrel failed:/);
        return true;
      },
    );
    assert.match(readFileSync(join(healthy, "index.ts"), "utf8"), /export \* as graph from/);
  });

  it("reports a reserved hand-written folder barrel path", () => {
    const directory = fixturePackage("reserved");
    mkdirSync(join(directory, "src", "example"), { recursive: true });
    writeFileSync(join(directory, "src", "example", "one.ts"), "export const one = 1;\n");
    writeFileSync(join(directory, "index.example.ts"), "export const manual = true;\n");

    assert.throws(
      () => generateBarrels({ dirs: [directory] }),
      (error: unknown) => {
        assert.ok(error instanceof AggregateError);
        assert.match(
          String(error.errors[0]),
          /Generated barrel path is owned by a hand-written file/,
        );
        return true;
      },
    );
  });
});
