import {
  chmodSync,
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { basename, join, resolve } from "node:path";

const READONLY = 0o444;
const WRITABLE = 0o644;

const projectTable = (document) => {
  const project = document?.project;
  if (!project || typeof project !== "object" || Array.isArray(project)) {
    throw new Error("Missing Python project metadata");
  }
  return project;
};

const directSibling = (dependency, sibling) => {
  const prefix = `${sibling.name} @ git+`;
  if (!dependency.startsWith(prefix)) return false;
  const marker = "#subdirectory=";
  const markerIndex = dependency.indexOf(marker, prefix.length);
  if (markerIndex < 0) return false;
  const directory = dependency.slice(markerIndex + marker.length);
  return directory === sibling.directory || directory.endsWith(`/${sibling.directory}`);
};

const setWritable = (path) => {
  if (existsSync(path)) chmodSync(path, WRITABLE);
};

const setReadonly = (path) => {
  if (existsSync(path)) chmodSync(path, READONLY);
};

const generatedHeader = (crate) =>
  [
    "# GENERATED by UniFFI binding generation - DO NOT EDIT.",
    `# Regenerated from the ${crate} Rust exports.`,
    "# Hand edits are overwritten on the next watch; this file is read-only.",
    "",
  ].join("\n");

export const pythonProjectInfo = (source, toml) => {
  const document = toml.parse(source);
  const project = projectTable(document);
  if (typeof project.name !== "string" || !project.name) {
    throw new Error("Missing Python project name");
  }
  const config = document?.tool?.["dbx-tools"];
  return {
    name: project.name,
    private: Boolean(config && typeof config === "object" && config.private === true),
  };
};

export const stampPythonProject = (
  source,
  { packages, rewriteDependencies = true, toml, version },
) => {
  const marker = source.startsWith("# ") ? source.slice(0, source.indexOf("\n")) : undefined;
  const document = toml.parse(source);
  const project = projectTable(document);
  if (typeof project.version !== "string") {
    throw new Error("Missing Python project version");
  }
  project.version = version;
  if (rewriteDependencies) {
    const dependencies = project.dependencies;
    if (dependencies !== undefined && !Array.isArray(dependencies)) {
      throw new Error("Python project dependencies must be an array");
    }
    if (dependencies) {
      project.dependencies = dependencies.map((dependency) => {
        if (typeof dependency !== "string") {
          throw new Error("Python project dependencies must be strings");
        }
        const sibling = packages.find((candidate) => directSibling(dependency, candidate));
        return sibling ? `${sibling.name}==${version}` : dependency;
      });
    }
  }
  const body = toml.stringify(document).trimEnd();
  return `${marker ? `${marker}\n\n` : ""}${body}\n`;
};

export const pythonBindingGeneratorName = (crate, platform) =>
  `${crate}-uniffi-bindgen${platform === "win32" ? ".exe" : ""}`;

export const pythonBindingGeneratorArgs = ({ crate, library, output }) => [
  "generate",
  "--language",
  "python",
  "--crate",
  crate.replaceAll("-", "_"),
  "--out-dir",
  output,
  library,
];

export const installPythonBindings = ({
  crate,
  library,
  module,
  packageRoot,
  platform,
  readonly = false,
  run,
  targetDirectory,
}) => {
  const packageName = module.split(".").at(-1);
  if (!packageName) throw new Error(`Invalid Python module ${module}`);
  const packageDirectory = resolve(packageRoot, "src", ...module.split("."));
  const generatedDirectory = mkdtempSync(join(tmpdir(), `${packageName}-python-`));
  const generator = resolve(targetDirectory, pythonBindingGeneratorName(crate, platform));
  if (!existsSync(generator)) throw new Error(`Missing UniFFI generator ${generator}`);

  try {
    run(
      generator,
      pythonBindingGeneratorArgs({
        crate,
        library,
        output: generatedDirectory,
      }),
    );
    const generated = join(generatedDirectory, `${crate.replaceAll("-", "_")}.py`);
    if (!existsSync(generated)) throw new Error(`Missing generated binding ${generated}`);
    mkdirSync(packageDirectory, { recursive: true });

    const bindings = join(packageDirectory, "bindings.py");
    setWritable(bindings);
    writeFileSync(bindings, `${generatedHeader(crate)}${readFileSync(generated, "utf8")}`);

    const init = join(packageDirectory, "__init__.py");
    setWritable(init);
    writeFileSync(init, "");

    const nativeLibrary = join(packageDirectory, basename(library));
    setWritable(nativeLibrary);
    cpSync(library, nativeLibrary);

    if (readonly) {
      setReadonly(bindings);
      setReadonly(init);
      setReadonly(nativeLibrary);
    }
    rmSync(join(packageDirectory, "_generated"), { recursive: true, force: true });
    return { bindings, init, library: nativeLibrary };
  } finally {
    rmSync(generatedDirectory, { recursive: true, force: true });
  }
};
