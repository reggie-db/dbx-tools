import { execFile } from "node:child_process";
import { randomUUID } from "node:crypto";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, join } from "node:path";
import { promisify } from "node:util";

import { bin } from "@dbx-tools/core";

import { stringifyOpenapi } from "./render.ts";
import { DatabricksOpenapiError, type ArtifactPlan } from "./types.ts";

const SPEAKEASY_OPENAPI_VERSION = "1.24.0";
const SPEAKEASY_OPENAPI_RELEASE_URL = `https://github.com/speakeasy-api/openapi/releases/download/v${SPEAKEASY_OPENAPI_VERSION}`;
const execFileAsync = promisify(execFile);

interface StagedArtifact {
  plan: ArtifactPlan;
  temporaryRoot: string;
  specPath: string;
}

interface StagedClient {
  temporaryRoot: string;
  sourcePath: string;
}

interface ReplacedPath {
  target: string;
  backup?: string;
}

/** Injectable artifact tools used by focused pipeline tests. */
export interface ArtifactTools {
  validate?: (specPath: string) => void | Promise<void>;
  optimize?: (specPath: string) => void | Promise<void>;
}

function speakeasyAssetName(
  platform: NodeJS.Platform = process.platform,
  arch: string = process.arch,
): string {
  const osName =
    platform === "darwin"
      ? "Darwin"
      : platform === "linux"
        ? "Linux"
        : platform === "win32"
          ? "Windows"
          : undefined;
  const archName = arch === "arm64" ? "arm64" : arch === "x64" ? "x86_64" : undefined;
  if (!osName || !archName) {
    throw new DatabricksOpenapiError(
      `Speakeasy openapi has no release asset for ${platform}/${arch}`,
    );
  }
  return `openapi_${osName}_${archName}.${platform === "win32" ? "zip" : "tar.gz"}`;
}

async function speakeasyPath(): Promise<string> {
  const asset = speakeasyAssetName();
  const installed = await bin.ensure("openapi", `${SPEAKEASY_OPENAPI_RELEASE_URL}/${asset}`, {
    autoUnpackage: true,
    minVersion: SPEAKEASY_OPENAPI_VERSION,
    selector: ({ source }) =>
      join(source, process.platform === "win32" ? "openapi.exe" : "openapi"),
    versionParser: (output) => {
      const version = bin.parseVersion(output);
      return version === SPEAKEASY_OPENAPI_VERSION ? version : undefined;
    },
  });
  return installed.path;
}

function validateStructure(specPath: string): Record<string, unknown> {
  const document = JSON.parse(readFileSync(specPath, "utf8")) as Record<string, unknown>;
  if (document.openapi !== "3.0.3") {
    throw new DatabricksOpenapiError(`${specPath} must declare OpenAPI 3.0.3`);
  }
  if (!document.info || typeof document.info !== "object") {
    throw new DatabricksOpenapiError(`${specPath} has no info object`);
  }
  if (!document.paths || typeof document.paths !== "object") {
    throw new DatabricksOpenapiError(`${specPath} has no paths object`);
  }
  const components = document.components as Record<string, unknown> | undefined;
  if (!components || !components.schemas || !components.securitySchemes) {
    throw new DatabricksOpenapiError(`${specPath} has incomplete components`);
  }
  return document;
}

async function defaultValidate(specPath: string): Promise<void> {
  const executable = await speakeasyPath();
  await execFileAsync(executable, ["spec", "validate", specPath]);
}

async function defaultOptimize(specPath: string): Promise<void> {
  const executable = await speakeasyPath();
  await execFileAsync(executable, ["spec", "optimize", specPath, "--write", "--non-interactive"]);
}

function writable(path: string): void {
  if (existsSync(path)) chmodSync(path, 0o644);
}

function readonly(path: string): void {
  chmodSync(path, 0o444);
}

function rustModuleName(output: string): string {
  return output.replaceAll("-", "_");
}

function rustClientSource(plans: ArtifactPlan[]): string {
  const sortedPlans = [...plans].sort((left, right) => left.output.localeCompare(right.output));
  const modules = sortedPlans
    .map(
      (plan) => `/// Client generated from the pinned ${plan.output} OpenAPI document.
pub mod ${rustModuleName(plan.output)} {
    progenitor::generate_api!(
        spec = "assets/openapi/${plan.output}/openapi.json",
        interface = Builder
    );
}`,
    )
    .join("\n\n");
  const fields = sortedPlans
    .map((plan) => {
      const moduleName = rustModuleName(plan.output);
      return `    /// Generated ${plan.output} API client.
    pub ${moduleName}: ${moduleName}::Client,`;
    })
    .join("\n");
  const initializers = sortedPlans
    .map((plan) => {
      const moduleName = rustModuleName(plan.output);
      return `            ${moduleName}: ${moduleName}::Client::new_with_client(
                base_url,
                http_client.clone(),
            ),`;
    })
    .join("\n");
  return `// Generated by @dbx-tools/databricks-openapi. Do not edit.
//! Databricks API clients generated from pinned modular SDK contracts.

#![allow(missing_docs)]
#![allow(clippy::all)]

${modules}

/// Databricks API clients sharing one HTTP connection pool and base URL.
pub struct Client {
${fields}
}

impl Client {
    /// Construct all API clients with a new default HTTP client.
    pub fn new(base_url: &str) -> Self {
        Self::new_with_client(base_url, reqwest::Client::new())
    }

    /// Construct all API clients from one shared HTTP client.
    pub fn new_with_client(base_url: &str, http_client: reqwest::Client) -> Self {
        Self {
${initializers}
        }
    }
}
`;
}

async function stageArtifact(plan: ArtifactPlan, tools: ArtifactTools): Promise<StagedArtifact> {
  const parent = dirname(plan.rustSpecPath);
  mkdirSync(parent, { recursive: true });
  const temporaryRoot = mkdtempSync(join(parent, ".openapi-stage-"));
  const specPath = join(temporaryRoot, "openapi.json");
  try {
    writeFileSync(specPath, stringifyOpenapi(plan.document));
    validateStructure(specPath);
    await (tools.validate ?? defaultValidate)(specPath);
    await (tools.optimize ?? defaultOptimize)(specPath);
    validateStructure(specPath);
    await (tools.validate ?? defaultValidate)(specPath);
    readonly(specPath);
    return { plan, temporaryRoot, specPath };
  } catch (cause) {
    rmSync(temporaryRoot, { recursive: true, force: true });
    throw cause;
  }
}

function stageRustClient(plans: ArtifactPlan[], rustClientPath: string): StagedClient {
  const parent = dirname(rustClientPath);
  mkdirSync(parent, { recursive: true });
  const temporaryRoot = mkdtempSync(join(parent, ".openapi-client-stage-"));
  const sourcePath = join(temporaryRoot, basename(rustClientPath));
  writeFileSync(sourcePath, rustClientSource(plans));
  readonly(sourcePath);
  return { temporaryRoot, sourcePath };
}

function replacePath(source: string, target: string): ReplacedPath {
  mkdirSync(dirname(target), { recursive: true });
  let backup: string | undefined;
  if (existsSync(target)) {
    writable(target);
    backup = join(dirname(target), `.${basename(target)}-backup-${randomUUID()}`);
    renameSync(target, backup);
  }
  try {
    renameSync(source, target);
  } catch (cause) {
    if (backup) renameSync(backup, target);
    throw cause;
  }
  return { target, backup };
}

function rollback(replacements: ReplacedPath[]): void {
  for (const replacement of [...replacements].reverse()) {
    rmSync(replacement.target, { recursive: true, force: true });
    if (replacement.backup) renameSync(replacement.backup, replacement.target);
  }
}

function removeBackups(replacements: ReplacedPath[]): void {
  for (const replacement of replacements) {
    if (replacement.backup) rmSync(replacement.backup, { recursive: true, force: true });
  }
}

function commitArtifacts(
  staged: StagedArtifact[],
  client: StagedClient,
  rustClientPath: string,
): void {
  const replacements: ReplacedPath[] = [];
  try {
    for (const artifact of staged) {
      replacements.push(replacePath(artifact.specPath, artifact.plan.rustSpecPath));
    }
    replacements.push(replacePath(client.sourcePath, rustClientPath));
  } catch (cause) {
    rollback(replacements);
    throw cause;
  }
  removeBackups(replacements);
}

/** Stage every JSON contract and the generated Rust module before committing either. */
export async function writeOpenapiArtifacts(
  plans: ArtifactPlan[],
  rustClientPath: string,
  tools: ArtifactTools = {},
): Promise<string[]> {
  const staged: StagedArtifact[] = [];
  let client: StagedClient | undefined;
  try {
    for (const plan of plans) staged.push(await stageArtifact(plan, tools));
    client = stageRustClient(plans, rustClientPath);
    commitArtifacts(staged, client, rustClientPath);
    return [rustClientPath, ...plans.map((plan) => plan.rustSpecPath)];
  } finally {
    for (const artifact of staged) {
      rmSync(artifact.temporaryRoot, { recursive: true, force: true });
    }
    if (client) rmSync(client.temporaryRoot, { recursive: true, force: true });
  }
}
