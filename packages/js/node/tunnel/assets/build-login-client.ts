import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

const packageRoot = join(import.meta.dir, "..");
const outputPath = join(packageRoot, "src/generated/_login-client.ts");
const result = await Bun.build({
  entrypoints: [join(import.meta.dir, "login-client.ts")],
  format: "iife",
  minify: true,
  target: "browser",
  write: false,
});

if (!result.success || result.outputs.length !== 1) {
  for (const message of result.logs) console.error(message);
  throw new Error("unable to build the hosted login client");
}

const source = (await result.outputs[0]!.text()).replaceAll("</script", "<\\/script");
const generated = [
  "// GENERATED by assets/build-login-client.ts - DO NOT EDIT.",
  `export const LOGIN_CLIENT_SOURCE = ${JSON.stringify(source)};`,
  "",
].join("\n");

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated);
