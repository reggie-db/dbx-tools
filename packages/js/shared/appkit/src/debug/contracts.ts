import { z } from "zod";

/** Registered AppKit plugin name for browser debug capture. */
export const DEBUG_CAPTURE_PLUGIN_NAME = "debugCapture";

/** Route segment registered beneath the debug-capture plugin base path. */
export const DEBUG_CAPTURE_ROUTE = "/captures";

/** Default AppKit mount for the debug-capture plugin. */
export const DEBUG_CAPTURE_DEFAULT_BASE_PATH = "/api/debug-capture";

/** Build the browser debug-capture endpoint from a published plugin base path. */
export function debugCaptureRoute(basePath = DEBUG_CAPTURE_DEFAULT_BASE_PATH): string {
  return `${basePath.replace(/\/+$/, "")}${DEBUG_CAPTURE_ROUTE}`;
}

/** Scalar value allowed in debug capture metadata and event snapshots. */
export const DebugCaptureScalarSchema = z
  .union([z.string().max(500), z.number().finite(), z.boolean(), z.null()])
  .describe("Bounded scalar diagnostic value safe to serialize as JSON.");

/** Scalar value allowed in debug capture metadata and event snapshots. */
export type DebugCaptureScalar = z.infer<typeof DebugCaptureScalarSchema>;

/** One timestamped browser diagnostic event. */
export const DebugCaptureEventSchema = z
  .object({
    at: z
      .number()
      .finite()
      .nonnegative()
      .describe("Milliseconds elapsed since this capture started."),
    data: z
      .record(z.string().max(80), DebugCaptureScalarSchema)
      .optional()
      .describe("Browser, viewport, target, and selected element measurements."),
    sequence: z.number().int().nonnegative().describe("Monotonic event sequence number."),
    type: z.string().min(1).max(80).describe("Normalized browser or recorder event name."),
  })
  .strict()
  .describe("One browser debug-capture event.");

/** One timestamped browser diagnostic event. */
export type DebugCaptureEvent = z.infer<typeof DebugCaptureEventSchema>;

/** Bounded event batch accepted by append and stop requests. */
export const DebugCaptureEventsSchema = z
  .array(DebugCaptureEventSchema)
  .max(200)
  .describe("Ordered browser diagnostic events uploaded in one request.");

/** Capture identifier generated by the AppKit debug plugin. */
export const DebugCaptureIdSchema = z
  .string()
  .regex(/^vp-[a-z0-9]+-[a-f0-9]{8}$/)
  .describe("Opaque browser debug-capture identifier.");

/** Request body accepted by the debug-capture route. */
export const DebugCaptureRequestSchema = z
  .discriminatedUnion("action", [
    z
      .object({
        action: z.literal("start").describe("Start a new capture."),
        metadata: z
          .record(z.string().max(80), DebugCaptureScalarSchema)
          .describe("Initial application, route, device, and browser metadata."),
      })
      .strict(),
    z
      .object({
        action: z.literal("append").describe("Append buffered events."),
        captureId: DebugCaptureIdSchema,
        events: DebugCaptureEventsSchema,
      })
      .strict(),
    z
      .object({
        action: z.literal("stop").describe("Append final events and close the capture."),
        captureId: DebugCaptureIdSchema,
        events: DebugCaptureEventsSchema,
      })
      .strict(),
  ])
  .describe("Start, append, or stop request for a browser debug capture.");

/** Request body accepted by the debug-capture route. */
export type DebugCaptureRequest = z.infer<typeof DebugCaptureRequestSchema>;

/** Response returned after starting a browser debug capture. */
export const DebugCaptureStartResponseSchema = z
  .object({
    captureId: DebugCaptureIdSchema,
  })
  .strict()
  .describe("New browser debug-capture identifier.");

/** Response returned after appending browser debug events. */
export const DebugCaptureAppendResponseSchema = z
  .object({
    ok: z.literal(true).describe("Whether the event batch was persisted."),
  })
  .strict()
  .describe("Browser debug-capture append result.");

/** Response returned after stopping a browser debug capture. */
export const DebugCaptureStopResponseSchema = z
  .object({
    captureId: DebugCaptureIdSchema,
    ok: z.literal(true).describe("Whether the capture was closed."),
  })
  .strict()
  .describe("Completed browser debug-capture result.");

/** Browser-safe configuration published by the AppKit debug-capture plugin. */
export const DebugCaptureClientConfigSchema = z
  .object({
    basePath: z.string().min(1).describe("AppKit mount containing the capture route."),
  })
  .strict()
  .describe("Browser-safe AppKit debug-capture configuration.");

/** Browser-safe configuration published by the AppKit debug-capture plugin. */
export type DebugCaptureClientConfig = z.infer<typeof DebugCaptureClientConfigSchema>;
