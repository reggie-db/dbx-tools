#!/usr/bin/env -S bun
import { chmodSync, existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import type { BunPlugin } from "bun";
import stdLibBrowser from "node-stdlib-browser";

const packageRoot = dirname(fileURLToPath(import.meta.url));
const shimRoot = resolve(packageRoot, "shims");
const output = resolve(packageRoot, "src/dbx_tools/node_runtime/runtime.js");
const entry = "dbx-tools:node-runtime";
const standardAliases = stdLibBrowser as Record<string, string | undefined>;
const check = process.argv.includes("--check");
const generatedHeader = [
  "// GENERATED by packages/py/node-runtime/build-runtime.ts - DO NOT EDIT.",
  "// Regenerated from the package-owned shims directory.",
  "// Hand edits are overwritten; this file is read-only.",
].join("\n");

const plugin: BunPlugin = {
  name: "dbx-tools-node-runtime",
  setup(build) {
    build.onResolve({ filter: /^dbx-tools:node-runtime$/ }, () => ({
      path: entry,
      namespace: "dbx-tools-node-runtime",
    }));
    build.onLoad({ filter: /.*/, namespace: "dbx-tools-node-runtime" }, () => ({
      contents: runtimeEntry(),
      loader: "ts",
    }));
    build.onResolve({ filter: /.*/ }, ({ path }) => {
      const moduleName = path.replace(/^node:/, "");
      const standard = standardAliases[moduleName];
      return standard
        ? { path: Bun.resolveSync(standard, dirname(fileURLToPath(import.meta.url))) }
        : undefined;
    });
  },
};

const result = await Bun.build({
  entrypoints: [entry],
  format: "cjs",
  minify: false,
  plugins: [plugin],
  target: "browser",
  write: false,
});

if (!result.success) {
  for (const message of result.logs) {
    throw new Error(String(message));
  }
  throw new Error("Could not build the shared PythonMonkey runtime");
}
if (result.outputs.length !== 1) {
  throw new Error(`Expected one shared runtime output, received ${result.outputs.length}`);
}
const bundle = (await result.outputs[0].text()).replace(/[ \t]+$/gm, "").trimEnd();
const contents = `${generatedHeader}\n\n${bundle}\n`;
const current = existsSync(output) ? readFileSync(output, "utf8") : undefined;
if (check) {
  if (current !== contents) {
    throw new Error(`Generated Node runtime is stale: ${relative(process.cwd(), output)}`);
  }
} else if (current !== contents) {
  if (existsSync(output)) chmodSync(output, 0o644);
  writeFileSync(output, contents);
}
if (existsSync(output)) chmodSync(output, 0o444);

function runtimeEntry(): string {
  const moduleImports = shimModules();
  const registryKeys = new Map<string, string>();
  const moduleKeys = moduleImports.flatMap(({ file, ident, specifier }) => {
    const rest = specifier.replace(/^[^:]+:/, "");
    return [specifier, ...(rest && rest !== specifier ? [rest] : [])].map((key) => {
      const existing = registryKeys.get(key);
      if (existing) {
        throw new Error(`Runtime shim key ${key} is provided by both ${existing} and ${file}`);
      }
      registryKeys.set(key, file);
      return `  ${JSON.stringify(key)}: ${ident},`;
    });
  });
  return [
    `import ${JSON.stringify(resolve(shimRoot, "bootstrap.ts"))};`,
    ...moduleImports.map(
      ({ ident, file }) => `import * as ${ident} from ${JSON.stringify(resolve(shimRoot, file))};`,
    ),
    "",
    'const RUNTIME_KEY = Symbol.for("@dbx-tools/node-runtime/runtime");',
    "const ABI_VERSION = 1;",
    "const globals = globalThis;",
    "const current = globals[RUNTIME_KEY];",
    "if (current && current.abiVersion !== ABI_VERSION) {",
    "  throw new Error(`Python Node runtime ABI ${current.abiVersion} is incompatible with ${ABI_VERSION}`);",
    "}",
    "const modules = Object.freeze({",
    ...moduleKeys,
    "});",
    "const runtime = current ?? Object.freeze({ abiVersion: ABI_VERSION, modules });",
    "globals[RUNTIME_KEY] = runtime;",
    "export const __pythonRuntimeAbiVersion = ABI_VERSION;",
    "export const __pythonRuntime = runtime;",
    "export const __pythonBuiltin = (name) => {",
    "  const module = runtime.modules[name];",
    "  if (!module) throw new Error(`Unknown runtime shim: ${name}`);",
    "  return module;",
    "};",
  ].join("\n");
}

function shimModules(): readonly { file: string; ident: string; specifier: string }[] {
  const shims = shimTypeScriptFiles(shimRoot)
    .sort()
    .flatMap((file) => {
      const shim = shimFromFile(file);
      return shim ? [shim] : [];
    });
  const specifiers = new Map<string, string>();
  for (const shim of shims) {
    const existing = specifiers.get(shim.specifier);
    if (existing) {
      throw new Error(
        `Runtime shim specifier ${shim.specifier} is derived from both ${existing} and ${shim.file}`,
      );
    }
    specifiers.set(shim.specifier, shim.file);
  }
  return shims;
}

function shimTypeScriptFiles(directory: string): string[] {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return shimTypeScriptFiles(path);
    return entry.name.endsWith(".ts") ? [relative(shimRoot, path)] : [];
  });
}

function shimFromFile(
  file: string,
): { file: string; ident: string; specifier: string } | undefined {
  const base = file.replace(/\.ts$/, "").replaceAll("\\", "/");
  const specifier = base.replaceAll("___", ":").replaceAll("__", "/");
  if (!specifier.includes(":")) return undefined;
  return {
    file,
    ident: `_${base.replaceAll(/[^A-Za-z0-9]/g, "_")}`,
    specifier,
  };
}
