import { spawnSync } from "node:child_process";
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";
import { parseArgs } from "node:util";
import { addExplicitInterfaceReexports, addTypeScriptExtensionsToBindingImports, makeDefaultedInterfaceParametersOptional } from "./uniffi.ts";

const names = ["output", "library", "ubrn", "python-generator", "cargo", "rustc", "crate", "node-package", "python-module", "configs", "node-packages"];
const { values } = parseArgs({ options: Object.fromEntries(names.map(name => [name, { type: "string" }])) });
if (process.env.JS_BINARY__EXECROOT) process.chdir(process.env.JS_BINARY__EXECROOT);
const output = resolve(values.output);
const library = resolve(values.library);
const cargo = resolve(values.cargo);
const rustc = resolve(values.rustc);
const ubrn = resolve(values.ubrn);
const pythonGenerator = resolve(values["python-generator"]);
const configs = Object.fromEntries(Object.entries(JSON.parse(values.configs)).map(([name, file]) => [name, resolve(file)]));
const packages = JSON.parse(values["node-packages"]);
const temporary = join(output, ".metadata");
const nodeOutput = join(output, "node");
mkdirSync(nodeOutput, { recursive: true });
mkdirSync(temporary, { recursive: true });
writeFileSync(join(temporary, "Cargo.toml"), `[workspace]\nresolver = "2"\nmembers = ${JSON.stringify(Object.keys(configs))}\n`);
for (const [name, config] of Object.entries(configs)) {
  const directory = join(temporary, name);
  mkdirSync(directory, { recursive: true });
  writeFileSync(join(directory, "Cargo.toml"), `[package]\nname = "${name.replaceAll("_", "-")}"\nversion = "0.0.0"\nedition = "2021"\n[lib]\nname = "${name}"\npath = "lib.rs"\n`);
  writeFileSync(join(directory, "lib.rs"), "");
  cpSync(config, join(directory, "uniffi.toml"));
}
const run = (command, args) => {
  const result = spawnSync(command, args, {
    cwd: temporary,
    env: { ...process.env, CARGO: cargo, RUSTC: rustc, CARGO_HOME: join(temporary, ".cargo"), CARGO_NET_OFFLINE: "true" },
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  });
  if (result.error || result.status !== 0) throw new Error(`${basename(command)} failed: ${result.error?.message ?? result.stderr ?? result.stdout}`.replace(/\p{Extended_Pictographic}/gu, ""));
};
run(ubrn, ["generate", "napi", "bindings", "--library", "--no-format", "--ts-dir", nodeOutput, "--lib-colocated", library]);
const crate = values.crate;
for (const file of readdirSync(nodeOutput).filter(file => file.endsWith(".ts"))) {
  let source = readFileSync(join(nodeOutput, file), "utf8");
  for (const [namespace, packageName] of Object.entries(packages)) {
    if (namespace === crate) continue;
    source = source.replace(new RegExp(`import (\\w+) from ["']\\./${namespace}["'];`, "g"), `import { uniffiModule as $1 } from "${packageName}";`)
      .replaceAll(`'./${namespace}'`, `'${packageName}'`).replaceAll(`"./${namespace}"`, `"${packageName}"`);
  }
  writeFileSync(join(nodeOutput, file), source);
}
const ownModules = ["_bindings.ts", "_bindings-ffi.ts"];
const modules = ownModules.map((file, index) => {
  const generated = join(nodeOutput, `${crate}${index ? "-ffi" : ""}.ts`);
  return { specifier: `./${file}`, source: makeDefaultedInterfaceParametersOptional(readFileSync(generated, "utf8").replaceAll(`./${crate}-ffi`, "./_bindings-ffi")) };
});
const facade = addExplicitInterfaceReexports([
  "export * from './_bindings.ts';",
  "import uniffiModule from './_bindings.ts';",
  "uniffiModule.initialize();",
  "export { uniffiModule };",
  "export async function uniffiInitAsync() {}",
  "",
].join("\n"), modules);
for (const file of readdirSync(nodeOutput)) rmSync(join(nodeOutput, file), { recursive: true, force: true });
const header = `// GENERATED by UniFFI binding generation - DO NOT EDIT.\n// Regenerated from the ${crate.replaceAll("_", "-")} Rust exports.\n// Hand edits are overwritten on regeneration; this file is read-only.\n\n/* eslint-disable */\n// @ts-nocheck\n`;
for (const [file, source] of [["bindings.ts", facade], ...modules.map((module, index) => [ownModules[index], module.source])]) {
  writeFileSync(join(nodeOutput, file), header + addTypeScriptExtensionsToBindingImports(source).replace(/[ \t]+$/gm, ""));
}
if (values["python-module"]) {
  const pythonOutput = join(output, "python");
  mkdirSync(pythonOutput, { recursive: true });
  run(pythonGenerator, ["generate", "--language", "python", "--crate", crate, "--config", configs[crate], "--no-format", "--out-dir", pythonOutput, library]);
  const source = readFileSync(join(pythonOutput, `${crate}.py`), "utf8");
  writeFileSync(join(pythonOutput, "bindings.py"), `# GENERATED by UniFFI binding generation - DO NOT EDIT.\n${source}`);
  rmSync(join(pythonOutput, `${crate}.py`));
  writeFileSync(join(pythonOutput, "__init__.py"), "");
}
mkdirSync(join(output, "native"), { recursive: true });
cpSync(library, join(output, "native", basename(library)));
writeFileSync(join(output, "manifest.json"), JSON.stringify({ node: values["node-package"], python: values["python-module"] }));
rmSync(temporary, { recursive: true, force: true });
