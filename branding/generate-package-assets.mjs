#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const READONLY = 0o444;
const WRITABLE = 0o644;
const brandingRoot = path.dirname(fileURLToPath(import.meta.url));
const sourceRoot = path.join(brandingRoot, "assets");
const targetRoot = path.resolve(
  brandingRoot,
  "..",
  "packages/js",
  "ui",
  "branding",
  "src",
  "generated",
);
const rustAssetRoot = path.resolve(brandingRoot, "..", "packages/rs/databricks/assets");
const assets = ["icon-light.svg", "icon-dark.svg", "logo-light.svg", "logo-dark.svg"];

function writeReadonly(target, contents, encoding = "utf8") {
  if (fs.existsSync(target)) fs.chmodSync(target, WRITABLE);
  fs.writeFileSync(target, contents, encoding);
  fs.chmodSync(target, READONLY);
}

function copyReadonly(source, target) {
  writeReadonly(target, fs.readFileSync(source));
}

fs.mkdirSync(targetRoot, { recursive: true });
fs.mkdirSync(rustAssetRoot, { recursive: true });

const sourceByName = Object.fromEntries(
  assets.map((name) => {
    const source = fs.readFileSync(path.join(sourceRoot, name), "utf8");
    copyReadonly(path.join(sourceRoot, name), path.join(targetRoot, name));
    return [name, source];
  }),
);

const camel = (name) =>
  name.replace(/\.svg$/, "").replace(/-([a-z])/g, (_, char) => char.toUpperCase());
const svgEntries = assets
  .map((name) => `  ${camel(name)}: ${JSON.stringify(sourceByName[name])},`)
  .join("\n");
const urlEntries = assets
  .map((name) => {
    const dataUrl = `data:image/svg+xml;base64,${Buffer.from(sourceByName[name]).toString("base64")}`;
    return `  ${camel(name)}: ${JSON.stringify(dataUrl)},`;
  })
  .join("\n");

writeReadonly(
  path.join(targetRoot, "assets.ts"),
  [
    "// Generated from branding/assets by branding/generate-package-assets.mjs.",
    "// Do not edit this file or the neighboring generated SVG copies.",
    "",
    "export const dbxToolsAssetSvg = {",
    svgEntries,
    "} as const;",
    "",
    "export const dbxToolsAssetDataUrls = {",
    urlEntries,
    "} as const;",
    "",
  ].join("\n"),
);

const sourceBrand = fs.readFileSync(path.join(brandingRoot, "brand.yaml"), "utf8");
const brandHeader = [
  "# GENERATED by branding/generate-package-assets.mjs - DO NOT EDIT.",
  "# Regenerated from branding/brand.yaml.",
  "",
].join("\n");
writeReadonly(
  path.join(rustAssetRoot, "brand.yaml"),
  sourceBrand.startsWith("# GENERATED") ? sourceBrand : `${brandHeader}${sourceBrand}`,
);
copyReadonly(path.join(sourceRoot, "logo-light.svg"), path.join(rustAssetRoot, "logo-light.svg"));

console.log(
  `Generated ${assets.length} package assets in ${path.relative(process.cwd(), targetRoot)} and Rust copies in ${path.relative(process.cwd(), rustAssetRoot)}`,
);
